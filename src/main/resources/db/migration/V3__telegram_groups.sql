CREATE TABLE telegram_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    participant_id BIGINT NOT NULL REFERENCES participants(id),
    first_name VARCHAR(100) NOT NULL,
    active BOOLEAN NOT NULL,
    share_progress BOOLEAN NOT NULL DEFAULT FALSE,
    response_format VARCHAR(10) NOT NULL DEFAULT 'text',
    timezone VARCHAR(100) NOT NULL DEFAULT 'UTC',
    interests VARCHAR(500) NOT NULL DEFAULT '',
    last_message_id BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_telegram_member UNIQUE(chat_id, user_id),
    CONSTRAINT uq_telegram_participant UNIQUE(participant_id)
);

CREATE TABLE telegram_habit_links (
    habit_id BIGINT PRIMARY KEY REFERENCES habits(id),
    membership_id BIGINT NOT NULL REFERENCES telegram_memberships(id)
);

CREATE TABLE telegram_updates (
    update_id BIGINT PRIMARY KEY,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE telegram_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL,
    reply_to_message_id BIGINT,
    recipient_user_id BIGINT,
    message_thread_id BIGINT,
    response_text VARCHAR(4000) NOT NULL,
    response_format VARCHAR(10) NOT NULL DEFAULT 'text',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lease_until TIMESTAMP WITH TIME ZONE,
    lease_token VARCHAR(40),
    last_error_code VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_telegram_outbox_delivery ON telegram_outbox(status, available_at);
