ALTER TABLE telegram_memberships ADD COLUMN ai_consent BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE telegram_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL REFERENCES telegram_memberships(id),
    message_id BIGINT NOT NULL,
    message_thread_id BIGINT,
    message_text VARCHAR(4096),
    voice_file_id VARCHAR(512),
    input_kind VARCHAR(5) NOT NULL DEFAULT 'TEXT',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempts INTEGER NOT NULL DEFAULT 0,
    lease_until TIMESTAMP WITH TIME ZONE,
    lease_token VARCHAR(40),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_telegram_conversations_work ON telegram_conversations(status,created_at);
-- Aggregate usage survives profile deletion, without storing any participant identity.
CREATE TABLE telegram_ai_daily_totals (day_utc DATE PRIMARY KEY, accepted_requests INTEGER NOT NULL);
-- Content-free pseudonymous speech counters expire after at most two UTC days.
CREATE TABLE telegram_ai_speech_usage (
    day_utc DATE NOT NULL,
    user_key VARCHAR(64) NOT NULL,
    synthesis_requests INTEGER NOT NULL,
    PRIMARY KEY (day_utc,user_key)
);
